"""Split the engineer's theme.css into: vendor/bootstrap.css (verbatim) and
blocks.css (engineer's custom layer with every brand literal swapped for a token)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'source' / 'theme.css').read_text().split('\n')
split = 12843                       # line where the engineer's custom layer begins
(root / 'vendor').mkdir(exist_ok=True)
(root / 'vendor' / 'bootstrap.css').write_text('\n'.join(src[:split]) + '\n')
css = '\n'.join(src[split:])

# 1. drop the engineer's brand :root block (replaced by tokens.css)
css = re.sub(r':root \{\s*/\* Theme Customization \*/.*?\n\}\n', '', css, count=1, flags=re.S)

# 2. fonts: headings vs body vs rate numerals
css = css.replace('h1, .h1, h2, .h2, h3, .h3, h4, .h4, h5, .h5, h6, .h6 {\n  font-family: var(--source-sans);',
                  'h1, .h1, h2, .h2, h3, .h3, h4, .h4, h5, .h5, h6, .h6 {\n  font-family: var(--font-heading);')
css = css.replace('var(--source-sans)', 'var(--font-body)').replace('var(--source-serif)', 'var(--font-rate)')

# 3. colour variables
vmap = [('--sunset-dark','--color-accent-dark'),('--sunset','--color-accent'),('--denim','--color-dark'),
        ('--sky','--color-secondary'),('--granite','--color-tint'),('--haze-light','--color-tertiary-light'),
        ('--haze','--color-tertiary'),('--field','--color-highlight'),('--white','--color-white'),
        ('--black','--color-black'),('--roadtrip','--color-ink'),('--powder','--color-paper'),
        ('--linkblue','--color-link')]
for a,b in vmap: css = re.sub(r'var\(%s\)' % re.escape(a), 'var(%s)' % b, css)
css = re.sub(r'var\(--gray-(\d)\)', r'var(--color-gray-\1)', css)
css = re.sub(r'var\(--gray\)', 'var(--color-surface)', css)

# 4. literal hex values
hexmap = {'#f94d2b':'--color-accent','#c12000':'--color-accent-dark','#1c2b39':'--color-dark','#45bfe5':'--color-secondary',
 '#dddddc':'--color-tint','#4b56a8':'--color-tertiary','#838ddd':'--color-tertiary-light','#fdb913':'--color-highlight',
 '#f5f5f5':'--color-surface','#cccccc':'--color-gray-2','#ccc':'--color-gray-2','#979797':'--color-gray-3',
 '#bebebe':'--color-gray-4','#d9d9d9':'--color-gray-5','#a4a4a4':'--color-gray-6','#f9f9f9':'--color-gray-7',
 '#f8f9fa':'--color-surface-alt','#212529':'--color-body','#ffffff':'--color-white','#fff':'--color-white',
 '#000000':'--color-black','#000':'--color-black'}
def hx(m):
    k = m.group(0).lower()
    return 'var(%s)' % hexmap[k] if k in hexmap else m.group(0)
css = re.sub(r'#[0-9a-fA-F]{3,8}\b(?![0-9a-fA-F-])', hx, css)

# 5. radii + container width
for px, tok in [(2,'xs'),(4,'sm'),(5,'button'),(12,'md'),(16,'card'),(20,'lg'),(50,'pill')]:
    css = re.sub(r'(border-radius:\s*)%dpx\b' % px, r'\1var(--radius-%s)' % tok, css)
css = re.sub(r'(border-radius:\s*)50%', r'\1var(--radius-round)', css)
css = css.replace('--profileRadius: 16px', '--profileRadius: var(--radius-card)')
css = css.replace('max-width: 1440px;', 'max-width: var(--container-max);')

css = css.replace('#007aff', 'var(--color-primary)')   # Swiper default theme colour -> brand primary

hdr = ('/* blocks.css - generated by tools/build_css.py from the engineer\'s theme.css (custom layer).\n'
       '   Brand literals are replaced with tokens from tokens.css. Do not edit by hand; edit the tokens. */\n')
(root / 'blocks.css').write_text(hdr + css)
left = re.findall(r'#[0-9a-fA-F]{3,8}\b', css)
print('lines', len(css.split('\n')), '| remaining hex literals:', sorted(set(left)))
